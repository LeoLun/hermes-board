// Build: runtime IIFE (inlined as text) + Desktop plugin bundle (desktop/plugin.js).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RUNTIME_ENTRY = join(ROOT, 'runtime', 'src', 'index.js');
const TOKENS_CSS = join(ROOT, 'runtime', 'card-tokens.css');
const DESKTOP_ENTRY = join(ROOT, 'desktop', 'src', 'index.jsx');
const DESKTOP_OUT = join(ROOT, 'desktop', 'plugin.js');

export async function buildRuntime({ minify = true } = {}) {
  const result = await esbuild.build({
    entryPoints: [RUNTIME_ENTRY],
    bundle: true,
    format: 'iife',
    target: 'chrome120',
    minify,
    write: false,
    legalComments: 'none',
    charset: 'utf8',
  });
  return { js: result.outputFiles[0].text.trim(), css: readFileSync(TOKENS_CSS, 'utf8') };
}

/** esbuild plugin exposing the runtime assets as `virtual:hb-runtime-assets`. */
export function runtimeAssetsPlugin(assets) {
  return {
    name: 'hb-runtime-assets',
    setup(build) {
      build.onResolve({ filter: /^virtual:hb-runtime-assets$/ }, (args) => ({ path: args.path, namespace: 'hb-assets' }));
      build.onLoad({ filter: /.*/, namespace: 'hb-assets' }, () => ({
        contents: `export const RUNTIME_JS = ${JSON.stringify(assets.js)};\nexport const TOKENS_CSS = ${JSON.stringify(assets.css)};\n`,
        loader: 'js',
      }));
    },
  };
}

export async function buildDesktop({ minify = false } = {}) {
  if (!existsSync(DESKTOP_ENTRY)) {
    console.log('skip desktop bundle: desktop/src/index.jsx not found');
    return null;
  }
  const assets = await buildRuntime();
  const result = await esbuild.build({
    entryPoints: [DESKTOP_ENTRY],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'chrome120',
    jsx: 'transform',
    jsxFactory: '__hbJsx',
    jsxFragment: '__hbFragment',
    minify,
    write: false,
    legalComments: 'none',
    charset: 'utf8',
    plugins: [runtimeAssetsPlugin(assets)],
    banner: { js: '// hermes-board desktop plugin — generated by `pnpm build`, do not edit.' },
  });
  const text = result.outputFiles[0].text;
  writeFileSync(DESKTOP_OUT, text);
  return { bytes: Buffer.byteLength(text), runtimeBytes: Buffer.byteLength(assets.js) };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const runtime = await buildRuntime();
  console.log(`runtime: ${Buffer.byteLength(runtime.js)} bytes js, ${Buffer.byteLength(runtime.css)} bytes css`);
  const desktop = await buildDesktop();
  if (desktop) console.log(`desktop/plugin.js: ${desktop.bytes} bytes`);
}
