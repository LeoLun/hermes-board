// Build: card runtime IIFE (inlined as text) + Desktop plugin bundle (desktop/plugin.js, committed — the
// unified package's Desktop half is loaded uncompiled, see desktop-plugin-sdk.md "Unified package").
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RUNTIME_ENTRY = join(ROOT, 'runtime', 'src', 'index.js');
const TOKENS_CSS = join(ROOT, 'runtime', 'card-tokens.css');
export const DESKTOP_ENTRY = join(ROOT, 'desktop', 'src', 'plugin.js');
export const DESKTOP_OUT = join(ROOT, 'desktop', 'plugin.js');
/** The only specifiers the Desktop runtime loader rewrites; anything else is refused at load time. */
export const EXTERNALS = ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime'];

export async function buildRuntime({ minify = true } = {}) {
  const result = await esbuild.build({
    entryPoints: [RUNTIME_ENTRY],
    bundle: true,
    format: 'iife',
    target: 'chrome120',
    minify,
    write: false,
    legalComments: 'none',
    charset: 'utf8',
  });
  return { js: result.outputFiles[0].text.trim(), css: readFileSync(TOKENS_CSS, 'utf8') };
}

/** esbuild plugin exposing the runtime assets as `virtual:card-runtime`. */
export function runtimeAssetsPlugin(assets) {
  return {
    name: 'hb-card-runtime',
    setup(build) {
      build.onResolve({ filter: /^virtual:card-runtime$/ }, (args) => ({ path: args.path, namespace: 'hb-assets' }));
      build.onLoad({ filter: /.*/, namespace: 'hb-assets' }, () => ({
        contents: `export const RUNTIME_JS = ${JSON.stringify(assets.js)};\nexport const TOKENS_CSS = ${JSON.stringify(assets.css)};\n`,
        loader: 'js',
      }));
    },
  };
}

/** Bundle the Desktop plugin. `write: false` returns the text only (used by check-bundle's freshness test). */
export async function buildDesktop({ minify = false, write = true, entry = DESKTOP_ENTRY, outfile = DESKTOP_OUT } = {}) {
  const assets = await buildRuntime();
  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'chrome120',
    external: EXTERNALS,
    minify,
    write: false,
    legalComments: 'none',
    charset: 'utf8',
    plugins: [runtimeAssetsPlugin(assets)],
    banner: { js: '// hermes-board desktop plugin — generated by `pnpm build` from desktop/src, do not edit.' },
  });
  const text = result.outputFiles[0].text;
  if (write) writeFileSync(outfile, text);
  return { text, bytes: Buffer.byteLength(text), runtimeBytes: Buffer.byteLength(assets.js), cssBytes: Buffer.byteLength(assets.css) };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const desktop = await buildDesktop();
  console.log(`runtime: ${desktop.runtimeBytes} bytes js, ${desktop.cssBytes} bytes css (inlined)`);
  console.log(`desktop/plugin.js: ${desktop.bytes} bytes`);
}
